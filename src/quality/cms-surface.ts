/** Verified against frontend 5aff6d1c on 2026-10-23: only these layouts mount
 * SeoContent and consume CMS intro_extra/faq. Re-audit when adding a slot. */
export const BODY_CMS_PATHS = ['/', '/sell', '/trades', '/comparison'] as const;
export function bodyCmsRenders(path: string): boolean {
  const normalized = path === '/' ? path : path.replace(/\/$/, '');
  return BODY_CMS_PATHS.includes(normalized as typeof BODY_CMS_PATHS[number]);
}
/** Item metadata is computed from inventory, not CMS overrides. Keep field-null
 * diagnostic opportunities; do not spend on invisible snippet writes. */
export function cmsWriteBlockReason(path: string, field: string | null): string | null {
  if ((field === 'title' || field === 'description') && /^\/(?:(?:rust|dota2)\/)?items\/[^/]+\/?$/.test(path)) {
    return 'unsupported CMS surface: item title/description are generated by the storefront; no CMS override is rendered';
  }
  if ((field === 'intro_extra' || field === 'faq') && !bodyCmsRenders(path)) {
    return 'unsupported CMS surface: page does not render CMS intro_extra/faq';
  }
  return null;
}
